using Microsoft.AspNetCore.Mvc;
using NSwag;
using NSwag.Generation.Processors.Security;
using CSharpAPIProject.Api.Services;
using CSharpAPIProject.Infrastructure.Data;
using NJsonSchema;
using CSharpAPIProject.Application.Interfaces.Services;

namespace Microsoft.Extensions.DependencyInjection;

public static class DependencyInjection
{
	public static IServiceCollection AddApiServices(this IServiceCollection services, IConfiguration configuration)
	{
		var clientUrl = configuration.GetSection("ClientUrl").Get<string[]>();
		Guard.Against.Null(clientUrl, message: "string 'ClientUrl' not found.");

		services.AddScoped<IJwtTokenGeneratorService, JwtTokenGeneratorService>();

		services.AddDatabaseDeveloperPageExceptionFilter();

		services.AddScoped<IUser, CurrentUser>();

		services.AddHttpContextAccessor();

		services.AddHealthChecks().AddDbContextCheck<ApplicationDbContext>();

		services.AddExceptionHandler<CustomExceptionHandler>();

		// Supress the built-in model validator used by ASP.Net.
		// We will be using our own validators.
		services.Configure<ApiBehaviorOptions>(options => options.SuppressModelStateInvalidFilter = true);

		// Configure Swagger document generation
		services.AddEndpointsApiExplorer();
		services.AddOpenApiDocument((configure, sp) =>
		{
			configure.Title = "CSharpAPIProject API";
			configure.SchemaSettings.SchemaType = SchemaType.OpenApi3;
			configure.SchemaSettings.GenerateEnumMappingDescription = true;

			configure.AddSecurity("bearer", new NSwag.OpenApiSecurityScheme
			{
				BearerFormat = "JWT",
				Scheme = "bearer",
				Type = OpenApiSecuritySchemeType.Http,
				Description = "A token generated by calling /api/Users/login"
			});
			configure.OperationProcessors.Add(new AspNetCoreOperationSecurityScopeProcessor("bearer"));
		});

		services.AddCors(o => o.AddPolicy("ReactClient", builder =>
		{
			builder.WithOrigins(clientUrl)
				.AllowAnyMethod()
				.AllowAnyHeader();
		}));


		return services;
	}
}
